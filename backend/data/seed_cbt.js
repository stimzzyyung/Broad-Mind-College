function buildTimetable(offset) {
  const days = {};
  WEEKDAYS.forEach((day, d) => {
    days[day] = PERIODS.map((_, p) => defaultSubjects[(p + d + offset) % defaultSubjects.length]);
  });
  return { periods: PERIODS, days };
}

